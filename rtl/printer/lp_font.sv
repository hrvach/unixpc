    Character generator for the printer's paper view (FPGA only): 8x8 glyphs of the printable ASCII characters, one block RAM used as a ROM.

    The glyph data is in roms/lp_font.mem (generated by tools/gen_lp_font.py, one line per character): it is read at start-up by $readmemh, the same way as
    the CPU's microcode and the boot ROM. Quartus reads roms/lp_font.mem (3B1.qsf defines LP_FONT_FILE); the simulators read the bare name from their working directory.

    Address: {character[6:0], row[2:0]}, row 0 at the top. Data: the 8 pixels of the row, bit 7 = leftmost. The data is valid one clock after the
    address.
*/
`ifndef LP_FONT_FILE
`define LP_FONT_FILE "lp_font.mem"
`endif
module lp_font
#(
    parameter INIT_FILE = `LP_FONT_FILE
)
(
    input            clk,
    input      [9:0] addr,
    output reg [7:0] q
);

reg [7:0] rom [0:1023];

initial $readmemh(INIT_FILE, rom);

always @(posedge clk)
    q <= rom[addr];

endmodule
